#!/usr/bin/env python3
"""
Evaluate RAG answer quality (faithfulness and answer relevance) using an HF judge.

Requires a gold set generated by generate_gold_set.py:
  [{"question", "ground_truth", "ground_truth_contexts", "source_pdf", "page"}, ...]

Usage (from project root):
    python tests/retriever-evaluation/answer_quality.py --qa tests/retriever-evaluation/gold_set.json
    python tests/retriever-evaluation/answer_quality.py --qa gold_set.json --mode all --out aq_results.json
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import requests

sys.path.insert(0, str(Path(__file__).parents[2]))

from dotenv import load_dotenv

load_dotenv(Path(__file__).parents[2] / ".env")

from src.config import settings  # noqa: E402
from src.evaluation.answer_quality import (  # noqa: E402
    MODES,
    evaluate_answer_quality_item,
    judge_available,
    summarize_answer_quality,
)
from src.evaluation.runner import load_qa_file  # noqa: E402
from src.inference.llm_adapters import HuggingFaceAdapter  # noqa: E402


def call_api(api: str, question: str, top_k: int, mode: str) -> dict:
    resp = requests.post(
        f"{api}/chat",
        json={"question": question, "top_k": top_k, "search_mode": mode, "persist": False},
        timeout=120,
    )
    resp.raise_for_status()
    return resp.json()


async def evaluate_mode(
    api: str,
    qa: list[dict],
    mode: str,
    top_k: int,
    judge: HuggingFaceAdapter,
    delay: float,
) -> list[dict]:
    results = []
    for i, item in enumerate(qa, start=1):
        question = item["question"]
        print(f"  [{i}/{len(qa)}] {question[:80]}")
        try:
            resp = call_api(api, question, top_k, mode)
        except Exception as exc:
            print(f"    -> api-error ({exc})")
            results.append(
                {
                    "id": i,
                    "question": question,
                    "source_pdf": item.get("source_pdf"),
                    "answer": None,
                    "chunks_returned": 0,
                    "faithfulness_score": None,
                    "faithfulness_reasoning": "api error",
                    "relevance_score": None,
                    "relevance_reasoning": "api error",
                }
            )
            continue

        answer = resp.get("answer") or ""
        chunks = resp.get("chunks") or []
        scores = await evaluate_answer_quality_item(judge, question, answer, chunks)
        f_score = scores.get("faithfulness_score")
        r_score = scores.get("relevance_score")
        if f_score is not None and r_score is not None:
            print(f"    -> faithfulness={f_score:.2f}  relevance={r_score:.2f}")
        else:
            print("    -> skipped or parse error")
        results.append(
            {
                "id": i,
                "question": question,
                "source_pdf": item.get("source_pdf"),
                "answer": answer,
                "chunks_returned": len(chunks),
                **scores,
            }
        )
        if delay > 0:
            time.sleep(delay)
    return results


def print_summary(mode_results: dict[str, list[dict]]) -> None:
    summary = summarize_answer_quality(mode_results)
    print(f"\n{'MODE':<12} {'Faithfulness':>13} {'Ans.Relevance':>14} {'Halluc.':>8} {'Scored':>7}")
    print("-" * 60)
    for mode, row in summary.items():
        if not row["sample_count"]:
            print(f"{mode:<12} {'N/A':>13} {'N/A':>14} {'N/A':>8} {'0':>7}")
            continue
        print(
            f"{mode:<12} {row['faithfulness']:>13.2f} {row['relevance']:>14.2f} "
            f"{row['hallucination_rate']:>8.2f} {row['sample_count']:>7}"
        )


async def _main_async(args: argparse.Namespace) -> int:
    qa, _ = load_qa_file(args.qa)
    print(f"Loaded {len(qa)} questions from {args.qa}")
    print(
        f"Judge model: {settings.hf_judge_model}  |  search mode: {args.mode}  |  top-k: {args.top_k}"
    )

    try:
        h = requests.get(f"{args.api}/health", timeout=10)
        body = h.json()
        if body.get("services", {}).get("database") is False:
            print("Warning: database unhealthy — results may be empty")
    except requests.exceptions.ConnectionError as exc:
        print(f"API unreachable: {exc}")
        return 1

    judge = HuggingFaceAdapter(
        model=settings.hf_judge_model,
        token=settings.hf_token,
        timeout=90,
    )
    modes_to_run = MODES if args.mode == "all" else [args.mode]
    all_results: dict[str, list[dict]] = {}

    for mode in modes_to_run:
        print(f"\n=== Mode: {mode} ===")
        all_results[mode] = await evaluate_mode(
            args.api,
            qa,
            mode,
            args.top_k,
            judge,
            args.delay,
        )

    print_summary(all_results)

    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            json.dump(all_results, f, indent=2, ensure_ascii=False)
        print(f"\nSaved to {args.out}")

    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Evaluate RAG answer quality using an HF judge model"
    )
    parser.add_argument("--qa", required=True, help="Path to gold set JSON")
    parser.add_argument("--api", default="http://localhost:8000", help="API base URL")
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument(
        "--mode",
        default="hybrid",
        help="Search mode: hybrid | semantic | keyword | all",
    )
    parser.add_argument("--delay", type=float, default=0.5, help="Seconds between judge calls")
    parser.add_argument("--out", default=None, help="Optional JSON output path")
    args = parser.parse_args()

    if not judge_available():
        print("Error: HF_TOKEN not set in .env")
        return 1

    import asyncio

    return asyncio.run(_main_async(args))


if __name__ == "__main__":
    sys.exit(main() or 0)
